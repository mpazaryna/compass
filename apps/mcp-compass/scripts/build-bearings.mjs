// Bake bearings into a generated module. Parses AND validates every bearing at
// build time via loadBearing (M1's build-time helper), then writes plain parsed
// objects. The Worker imports those objects and ships no YAML parser (M2 spec).
// A malformed bearing throws here, failing the build rather than a client's
// session. M1's serialization guarantee makes the embedded objects safe.
import { existsSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { loadBearing } from '@compass/core'

const here = dirname(fileURLToPath(import.meta.url))
// Authored bearings live at the REPO ROOT, one folder per bearing —
// `bearings/<slug>/bearing.yaml` plus whatever support files it grows, mirroring
// Orchestra's top-level `skills/<name>/` (SHE-18). Resolved from this script's
// own location, never cwd, so it holds under `pnpm bake`, `wrangler deploy`, and
// a test subprocess alike. The example fixtures in packages/core are
// schema-test-only and are not served (M3).
const dir = process.env.COMPASS_BEARINGS_DIR ?? resolve(here, '../../../bearings')

const entries = readdirSync(dir, { withFileTypes: true })

// A bearing that is never baked is never served, and nothing says so at runtime.
// So a YAML file left loose at the root fails the build instead of being
// silently skipped — that is the mistake the old flat layout trains an author
// into. `.yml` counts: a typo'd extension is exactly as silent an omission.
// All of them are named at once, so fixing a misplaced set takes one pass.
const loose = entries
  .filter((e) => e.isFile() && /\.ya?ml$/.test(e.name))
  .map((e) => e.name)
  .sort()

if (loose.length > 0) {
  const names = loose.map((f) => `"${f}"`).join(', ')
  throw new Error(
    `${names} ${loose.length === 1 ? 'sits' : 'sit'} loose in the bearings directory` +
      ` — a bearing lives at <slug>/bearing.yaml`,
  )
}

// Dot-directories are tooling debris (caches, editor state), never authored
// content. Treating one as a bearing home would fail the build with a message
// blaming an author for something they did not write.
const slugs = entries
  .filter((e) => e.isDirectory() && !e.name.startsWith('.'))
  .map((e) => e.name)
  .sort()

const bearings = slugs.map((slug) => {
  const file = resolve(dir, slug, 'bearing.yaml')
  if (!existsSync(file)) {
    throw new Error(
      `bearing home "${slug}" has no bearing.yaml — each bearing is a directory containing bearing.yaml`,
    )
  }
  return loadBearing(file)
})

const out = `// GENERATED by scripts/build-bearings.mjs — do not edit.
// Bearings parsed and validated at build time; the Worker imports these plain
// objects and ships no YAML parser. A malformed bearing fails the build.
import type { Bearing } from '@compass/core/types'

export const BEARINGS: Bearing[] = ${JSON.stringify(bearings, null, 2)}
`

writeFileSync(resolve(here, '../src/bearings.generated.ts'), out)
console.log(`baked ${bearings.length} parsed bearings: ${bearings.map((b) => b.bearing).join(', ')}`)
